"""Build the data semantic layer from the builder pack, the scene and data/semantic/knowledge.yaml.

Writes data/semantic/layer.yaml and data/semantic/plant.sqlite, and proves every join and the
pack's own dashboard figures on the data. Exits with an error if a proof fails.

    python pipeline/build_layer.py <builder_pack.xlsx> [web/data/scene.json]
"""
import datetime
import json
import sqlite3
import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "data" / "semantic"
MAX_VALUES = 30
HEADER = "# Generated by pipeline/build_layer.py. Edit knowledge.yaml instead.\n"


def scene_frame(path):
    items = json.loads(Path(path).read_text(encoding="utf8"))["items"]
    return pd.DataFrame([{"tag": i["tag"], "object_id": i["id"], "x": i["center"][0], "y": i["center"][1], "z": i["center"][2],
                          "mapping": i.get("mapping"), "mapping_conf": i.get("mapping_conf"), "matched": int(bool(i.get("matched")))}
                         for i in items if i.get("tag")])


def clean(frame, dropped):
    """Dates become ISO text and booleans become 0 or 1, because SQLite has neither type."""
    frame = frame.drop(columns=[c for c in frame.columns if c in dropped]).copy()
    for name in frame.columns:
        if pd.api.types.is_datetime64_any_dtype(frame[name]):
            text = frame[name].dt.strftime("%Y-%m-%d %H:%M:%S")
            frame[name] = text.str.removesuffix(" 00:00:00") if (frame[name].dt.normalize() == frame[name]).all() else text
        elif pd.api.types.is_bool_dtype(frame[name]):
            frame[name] = frame[name].astype(int)
    return frame


def describe_column(name, series, known):
    numeric = pd.api.types.is_numeric_dtype(series)
    dated = isinstance(series.dropna().iloc[0], str) and series.dropna().iloc[0][:4].isdigit() and series.dropna().iloc[0][4:5] == "-"
    role = "key" if name.endswith("_id") or name == "tag" else "date" if dated else "measure" if numeric else "attribute"
    column = {"name": name, "label": name.replace("_", " ").capitalize(), "role": role, "type": "number" if numeric else "text", **known}
    if column["role"] == "measure":
        column.setdefault("agg", "avg")
    if column["role"] in ("attribute", "key") and not numeric and series.nunique() <= MAX_VALUES:
        column["values"] = sorted(str(v) for v in series.dropna().unique())
    return column


def prove_joins(entities, db):
    today = datetime.date.today().isoformat()
    for entity in entities:
        for join in entity.get("joins", []):
            left, right = join["keys"]
            total, found = db.execute(f'SELECT COUNT(*), SUM("{left}" IN (SELECT "{right}" FROM "{join["to"]}")) FROM "{entity["name"]}"').fetchone()
            copies = db.execute(f'SELECT MAX(n) FROM (SELECT COUNT(*) n FROM "{join["to"]}" GROUP BY "{right}")').fetchone()[0]
            if found != total or copies != 1:
                sys.exit(f"join {entity['name']}.{join['name']} fails: {found} of {total} rows match, up to {copies} copies")
            join["verified"] = {"match_pct": 100.0, "checked_on": today}


def prove_dashboard(sheet, db):
    """Compare class counts and average health with the Dashboard sheet of the pack."""
    rows = sheet.iloc[:, 3:6].dropna()
    expected = {str(r.iloc[0]): (r.iloc[1], r.iloc[2]) for _, r in rows.iterrows() if str(r.iloc[0]) != "Asset class"}
    for cls, count, health in db.execute("SELECT asset_class, COUNT(*), ROUND(AVG(health_score), 1) FROM asset_state GROUP BY 1"):
        if cls not in expected or expected[cls][0] != count or abs(float(expected[cls][1]) - health) > 0.05:
            sys.exit(f"dashboard check fails for {cls}: {count} assets, health {health}, pack says {expected.get(cls)}")
    return len(expected)


def main(pack, scene):
    knowledge = yaml.safe_load((FOLDER / "knowledge.yaml").read_text(encoding="utf8"))
    sheets = pd.read_excel(pack, sheet_name=None)
    target = FOLDER / "plant.sqlite"
    target.unlink(missing_ok=True)
    db = sqlite3.connect(target)
    entities = []
    for entity in knowledge["entities"]:
        frame = scene_frame(scene) if entity["source"] == "scene" else sheets[entity["source"]]
        frame = clean(frame, knowledge["drop_columns"])
        if entity["name"] == "telemetry":
            frame.insert(1, "day", frame["timestamp"].str[:10])
        frame.to_sql(entity["name"], db, index=False)
        columns = [describe_column(c, frame[c], knowledge["columns"].get(c, {})) for c in frame.columns]
        entities.append({**entity, "columns": columns})
    prove_joins(entities, db)
    checked = prove_dashboard(sheets["Dashboard"], db)
    db.commit()
    layer = {"entities": entities, "recipes": knowledge["recipes"], "glossary": knowledge["glossary"]}
    (FOLDER / "layer.yaml").write_text(HEADER + yaml.safe_dump(layer, sort_keys=False, allow_unicode=True), encoding="utf8")
    joins = sum(len(e.get("joins", [])) for e in entities)
    print(f"{len(entities)} entities, {sum(len(e['columns']) for e in entities)} columns, {joins} joins at 100%, {checked} dashboard classes equal")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else ROOT / "web" / "data" / "scene.json")
